def curve(on, peak, off, h=1.0):
    return [round(h * (0 if w < on else min(1, (w - on) / max(peak - on, 1)) if w <= peak else max(0, 1 - (w - peak) / max(off - peak, 1)) if off else 1), 2) for w in wk]
