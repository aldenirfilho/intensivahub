def traj(kind):
    out = []
    for m in yrs:
        if kind == "c": v = 92 - 0.15 * m if m < 48 else 92 - 0.15 * 48 - 6.2 * (m - 48)
        elif kind == "o":
            v = 82 - 0.35 * m
            for e in (18, 33, 48): v -= 22 * math.exp(-((m - e) / 2.2) ** 2) + (9 if m > e else 0)
        else: v = 55 - 0.62 * m
        out.append(round(max(v, 2), 1))
    return out

